# Um tipo de dado é uma classificação que indica que tipo de valor temos
# e quais operações podem ser feitas com ele.

# Por exemplo:
# 2 é um número inteiro -> int
# "Antonio" é um texto -> str
# True é um valor lógico -> bool

2          # int
"Antonio" # str
True       # bool


# Alguns dos principais tipos de dados nativos do Python:

int   # números inteiros, sem casas decimais. Ex: 10
float # números com ponto decimal. Ex: 1.15
str   # texto, uma sequência de caracteres. Ex: "Eduardo"
bool  # valor lógico: True ou False
list  # coleção ordenada e mutável de itens. Ex: ["banana", "laranja", "maçã"]
tuple # coleção ordenada e imutável de itens. Ex: ("a", 1)
dict  # coleção de pares chave-valor. Ex: {"chave": "valor"}
set   # coleção de itens únicos. Ex: {"a", "b", "c"}
None  # representa a ausência de um valor


# Esses são tipos nativos do Python, ou seja, o Python já os conhece
# e sabe como trabalhar com eles.


# list, tuple, dict e set também são chamados de estruturas de dados
# porque servem para organizar e armazenar vários valores.